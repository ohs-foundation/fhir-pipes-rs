//! Generates `src/fhir_types.rs`, the FHIR type table behind
//! `fhir_model::TableModelProvider`, from the StructureDefinitions of one or
//! more FHIR core packages:
//!
//! ```text
//! cargo run -p fhir-pipes-sof --example generate_fhir_types -- \
//!     ~/.fhir/packages/hl7.fhir.r4.core#4.0.1/package \
//!     ~/.fhir/packages/hl7.fhir.r5.core#5.0.0/package \
//!     > crates/sof/src/fhir_types.rs
//! ```
//!
//! It reads the base definitions (resources, complex and primitive datatypes)
//! and the datatype profiles the core uses as element types (R4's `Age`,
//! `Duration`, `SimpleQuantity` and so on), and writes each type with its
//! kind and base types, and each element of its snapshot with its owner (the
//! type, or a backbone element's path such as `Observation.component`),
//! whether it repeats, and its type. With several packages it writes their
//! union, so views stay independent of the FHIR version:
//!
//! - an element in one version only is kept;
//! - an element that repeats in any version repeats;
//! - a choice element (`value[x]`, listed with its `[x]`) allows the types of
//!   every version;
//! - an element whose type differs between versions is `Unknown`, so the
//!   engine navigates it without type information.

use std::collections::{BTreeMap, BTreeSet};
use std::path::Path;

use serde_json::Value;

const FHIR_TYPE_EXT: &str = "http://hl7.org/fhir/StructureDefinition/structuredefinition-fhir-type";

#[derive(Clone, PartialEq)]
enum Ty {
    Named(String),
    Choice(BTreeSet<String>),
    Backbone(String),
    Unknown,
}

impl Ty {
    fn rust(&self) -> String {
        match self {
            Ty::Named(n) => format!("ElementType::Named({n:?})"),
            Ty::Choice(c) => format!("ElementType::Choice(&{:?})", c.iter().collect::<Vec<_>>()),
            Ty::Backbone(p) => format!("ElementType::Backbone({p:?})"),
            Ty::Unknown => "ElementType::Unknown".into(),
        }
    }
}

#[derive(Default)]
struct Table {
    /// type -> (kind, bases)
    types: BTreeMap<String, (String, BTreeSet<String>)>,
    /// (owner, element) -> (repeats, type)
    elements: BTreeMap<(String, String), (bool, Ty)>,
}

impl Table {
    fn add_type(&mut self, name: &str, kind: &str, base: Option<String>) {
        let entry = self
            .types
            .entry(name.to_string())
            .or_insert_with(|| (kind.to_string(), BTreeSet::new()));
        entry.1.extend(base);
    }

    fn add_element(&mut self, owner: String, name: String, repeats: bool, ty: Ty) {
        match self.elements.get_mut(&(owner.clone(), name.clone())) {
            None => {
                self.elements.insert((owner, name), (repeats, ty));
            }
            Some((r, t)) => {
                *r |= repeats;
                *t = match (std::mem::replace(t, Ty::Unknown), ty) {
                    (Ty::Choice(mut a), Ty::Choice(b)) => {
                        a.extend(b);
                        Ty::Choice(a)
                    }
                    (a, b) if a == b => a,
                    _ => Ty::Unknown,
                };
            }
        }
    }
}

fn main() {
    let packages: Vec<String> = std::env::args().skip(1).collect();
    assert!(
        !packages.is_empty(),
        "usage: generate_fhir_types <package dir>..."
    );
    let mut table = Table::default();
    let mut sources = Vec::new();
    for dir in &packages {
        sources.push(read_package(Path::new(dir), &mut table));
    }

    println!("// FHIR types and elements for `fhir_model::TableModelProvider`.");
    println!("// Generated by examples/generate_fhir_types.rs from:");
    for source in &sources {
        println!("//   {source}");
    }
    println!("// Do not edit; regenerate (see the example's header).");
    println!();
    println!("/// `(type, kind, base types)`, sorted by type.");
    println!("static TYPES: &[(&str, Kind, &[&str])] = &[");
    for (name, (kind, bases)) in &table.types {
        let kind = match kind.as_str() {
            "resource" => "Kind::Resource",
            "primitive-type" => "Kind::Primitive",
            _ => "Kind::Complex",
        };
        println!(
            "    ({name:?}, {kind}, &{:?}),",
            bases.iter().collect::<Vec<_>>()
        );
    }
    println!("];");
    println!();
    println!("/// `(owner, element, repeats, type)`, sorted by owner and element.");
    println!("static ELEMENTS: &[(&str, &str, bool, ElementType)] = &[");
    for ((owner, name), (repeats, ty)) in &table.elements {
        println!("    ({owner:?}, {name:?}, {repeats}, {}),", ty.rust());
    }
    println!("];");
}

/// Adds the package's types to `table`; returns the package's `name#version`.
fn read_package(dir: &Path, table: &mut Table) -> String {
    let manifest: Value =
        serde_json::from_str(&std::fs::read_to_string(dir.join("package.json")).unwrap()).unwrap();
    let mut definitions = Vec::new();
    for entry in std::fs::read_dir(dir).unwrap() {
        let path = entry.unwrap().path();
        let file = path.file_name().unwrap().to_string_lossy();
        if file.starts_with("StructureDefinition-") && file.ends_with(".json") {
            let sd: Value = serde_json::from_str(&std::fs::read_to_string(&path).unwrap()).unwrap();
            definitions.push(sd);
        }
    }

    // Every type code an element of a base definition uses: a datatype
    // profile is kept when the core uses it as a type (R4's Age, Duration).
    let mut used = BTreeSet::new();
    for sd in definitions.iter().filter(|sd| is_base(sd)) {
        for e in snapshot(sd) {
            for t in e["type"].as_array().into_iter().flatten() {
                used.extend(t["code"].as_str().map(str::to_string));
            }
        }
    }

    for sd in &definitions {
        let kind = sd["kind"].as_str().unwrap_or("");
        let name = if is_base(sd) {
            sd["type"].as_str()
        } else if kind == "complex-type"
            && sd["derivation"] == "constraint"
            && sd["type"] != "Extension"
            && sd["name"].as_str().is_some_and(|n| used.contains(n))
        {
            sd["name"].as_str()
        } else {
            None
        };
        let Some(name) = name else { continue };
        let base = sd["baseDefinition"]
            .as_str()
            .and_then(|b| b.rsplit('/').next())
            .map(str::to_string);
        table.add_type(name, kind, base);
        add_elements(sd, name, table);
    }

    format!(
        "{}#{}",
        manifest["name"].as_str().unwrap(),
        manifest["version"].as_str().unwrap()
    )
}

/// A base definition: a resource or datatype, not a profile or logical model.
fn is_base(sd: &Value) -> bool {
    matches!(
        sd["kind"].as_str(),
        Some("resource" | "complex-type" | "primitive-type")
    ) && sd["derivation"] != "constraint"
}

fn snapshot(sd: &Value) -> impl Iterator<Item = &Value> {
    sd["snapshot"]["element"].as_array().into_iter().flatten()
}

fn add_elements(sd: &Value, name: &str, table: &mut Table) {
    let elements: Vec<&Value> = snapshot(sd).collect();
    let paths: Vec<&str> = elements
        .iter()
        .map(|e| e["path"].as_str().unwrap())
        .collect();
    // A profile's paths start with the type it constrains (`Quantity.value`
    // in Age); list its elements under its own name.
    let root = paths[0];
    for (i, e) in elements.iter().enumerate().skip(1) {
        let path = paths[i];
        if e["max"] == "0" {
            continue;
        }
        let relative = &path[root.len() + 1..];
        let (owner, element) = match relative.rsplit_once('.') {
            Some((parent, element)) => (format!("{name}.{parent}"), element),
            None => (name.to_string(), relative),
        };
        let repeats = e["max"] != "1";
        let codes: Vec<String> = e["type"]
            .as_array()
            .into_iter()
            .flatten()
            .map(type_code)
            .collect();
        let has_children = paths
            .get(i + 1)
            .is_some_and(|next| next.starts_with(&format!("{path}.")));
        let (element, ty) = if element.ends_with("[x]") {
            (element.to_string(), Ty::Choice(codes.into_iter().collect()))
        } else if let Some(reference) = e["contentReference"].as_str() {
            // `#Questionnaire.item` (R4) or `<url>#Questionnaire.item` (R5).
            let target = reference.rsplit('#').next().unwrap();
            let target = target.strip_prefix(root).unwrap_or(target);
            (element.to_string(), Ty::Backbone(format!("{name}{target}")))
        } else if has_children {
            (
                element.to_string(),
                Ty::Backbone(format!("{owner}.{element}")),
            )
        } else if codes.len() == 1 {
            (element.to_string(), Ty::Named(codes[0].clone()))
        } else {
            (element.to_string(), Ty::Unknown)
        };
        table.add_element(owner, element, repeats, ty);
    }
}

/// An element type's name: the code, or for a FHIRPath system type the FHIR
/// type the extension names (`Resource.id` is `id`), else `System.<Type>`.
fn type_code(t: &Value) -> String {
    let code = t["code"].as_str().unwrap_or("?");
    match code.strip_prefix("http://hl7.org/fhirpath/") {
        None => code.to_string(),
        Some(system) => t["extension"]
            .as_array()
            .into_iter()
            .flatten()
            .find(|x| x["url"] == FHIR_TYPE_EXT)
            .and_then(|x| x["valueUrl"].as_str().or(x["valueUri"].as_str()))
            .map(str::to_string)
            .unwrap_or_else(|| system.to_string()),
    }
}
